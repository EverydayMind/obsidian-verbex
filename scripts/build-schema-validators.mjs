// Ajv is a development-time compiler only. Keep its options/error messages intact.
import fs from 'node:fs'
import { createRequire } from 'node:module'
import { build } from 'esbuild'

const require = createRequire(import.meta.url)
const Ajv = require('ajv')
const version = require('ajv/package.json').version
if (version !== '6.15.0')
  throw new Error(`Review Ajv generator upgrade: ${version}`)

const bundle = await build({
  stdin: {
    contents:
      "export { validatorDefinitions } from './src/validation/schemaDefinitions'",
    resolveDir: process.cwd(),
  },
  bundle: true,
  write: false,
  platform: 'node',
  format: 'cjs',
  plugins: [
    {
      name: 'development-locale-only',
      setup(build) {
        // Definitions accept an explicit locale. Obsidian's moment is only used by
        // their compatibility export's default locale, never by schema construction.
        build.onResolve({ filter: /^obsidian$/ }, () => ({
          path: 'obsidian',
          namespace: 'development-locale',
        }))
        build.onLoad({ filter: /.*/, namespace: 'development-locale' }, () => ({
          contents: "export const moment = { locale: () => 'en' }",
        }))
      },
    },
  ],
})
const module = { exports: {} }
// Development script; this code is never included in the plugin bundle.
new Function('module', 'exports', 'require', bundle.outputFiles[0].text)(
  module,
  module.exports,
  require,
)
const definitions = module.exports.validatorDefinitions()
const korean = module.exports.validatorDefinitions('ko')
if (JSON.stringify(definitions) !== JSON.stringify(korean)) {
  throw new Error(
    'Locale-dependent validation schemas require separate validators',
  )
}

const rules = [
  [
    'import/no-extraneous-dependencies',
    'fast-deep-equal is the existing pinned Ajv transitive helper used by its emitted const/enum checks',
  ],
  [
    'no-constant-condition',
    'Ajv emits constant success branches during schema compilation',
  ],
  [
    '@typescript-eslint/no-unsafe-argument, @typescript-eslint/no-unsafe-assignment, @typescript-eslint/no-unsafe-call, @typescript-eslint/no-unsafe-member-access, @typescript-eslint/no-unsafe-return',
    'Ajv 6 emits untyped schema checks and helper calls',
  ],
  ['no-var', 'Ajv function-scoped variable semantics must be preserved'],
  [
    'no-constant-binary-expression, no-self-compare, no-empty',
    'Ajv emits constant fallbacks, NaN checks and empty success branches',
  ],
  ['no-prototype-builtins', 'Ajv checks its generated schema property maps'],
  [
    'no-control-regex',
    'Schema patterns intentionally reject control characters',
  ],
  [
    '@typescript-eslint/no-unused-vars',
    'Ajv templates emit shared reference and error bookkeeping',
  ],
]
let output =
  '// Generated by scripts/build-schema-validators.mjs with Ajv 6.15.0. Do not edit.\n'
// These internal rules are absent from the public config. Inline rule settings
// avoid unused-disable errors there while keeping the exception file-local.
output +=
  '/* eslint @typescript-eslint/ban-ts-comment: ["error", {"ts-nocheck": false}], @typescript-eslint/restrict-plus-operands: "off", @typescript-eslint/restrict-template-expressions: "off" -- Preserve compiler output and exact error wording; validators.ts owns the typed boundary */\n'
output +=
  rules
    .map(([names, reason]) => `/* eslint-disable ${names} -- ${reason} */`)
    .join('\n') + '\n'
output +=
  '// @ts-nocheck -- Generated JavaScript; validators.ts provides the typed boundary.\n'
output +=
  "import type { ValidateFunction } from 'ajv'\nimport formatsFactory from 'ajv/lib/compile/formats'\nimport ucs2length from 'ajv/lib/compile/ucs2length'\nimport equal from 'fast-deep-equal'\n"
// Keep the original compiler options: disabling inlining changes schemaPath.
// Compile related roots together so recursive/reference functions are shared.
const groups = new Map()
for (const definition of definitions) {
  const key = JSON.stringify(definition.options)
  if (!groups.has(key)) groups.set(key, [])
  groups.get(key).push(definition)
}

// Schema objects are also runtime constants (enum/const/property maps). Reuse
// original JSON modules and point refVal at their subtrees instead of embedding
// a complete copy for every function and every inline reference.
const schemaModules = {
  bundle: 'md-dialect-v2/bundle-v3',
  record: 'md-dialect-v2/record-v2',
  structure: 'derive-structure-v1/structure',
  snapshot: 'v1/snapshot',
  profile: 'v1/profile',
  report: 'v1/derivation-report',
  profileV2: 'v2/profile',
  evidence: 'v2/semantic-evidence',
}
const data = new Map()
const schemaImports = []
function remember(value, expression) {
  const key = JSON.stringify(value)
  if (data.has(key)) return
  data.set(key, expression)
  if (value && typeof value === 'object') {
    for (const [key, child] of Object.entries(value))
      remember(child, `${expression}[${JSON.stringify(key)}]`)
  }
}
for (const [name, module] of Object.entries(schemaModules)) {
  schemaImports.push({
    name,
    path: `../../../contracts/report-style/${module}.schema.json`,
  })
  remember(
    definitions.find((definition) => definition.name === name).schema,
    `schema_${name}`,
  )
}
for (const name of ['prepare', 'produce', 'save']) {
  schemaImports.push({
    name,
    path: `../../../contracts/document-jobs/v1/${name}-request.schema.json`,
  })
  remember(
    definitions.find((definition) => definition.name === name).schema,
    `schema_${name}`,
  )
}
output +=
  '\n' +
  schemaImports
    .sort((a, b) => a.path.localeCompare(b.path))
    .map(({ name, path }) => `import schema_${name} from '${path}'\n`)
    .join('')
let dataIndex = 0
function schemaValue(value) {
  if (!value || typeof value !== 'object') return JSON.stringify(value)
  const key = JSON.stringify(value)
  if (!data.has(key)) {
    const name = `schemaData${dataIndex++}`
    output += `// prettier-ignore\nconst ${name} = ${JSON.stringify(value)};\n`
    remember(value, name)
  }
  return data.get(key)
}
for (const definition of definitions) schemaValue(definition.schema)

// A factory shares code, never mutable .errors or reference closures. Fast and
// full formats use RegExp/function respectively; dispatch without changing the
// actual format implementation passed to each validator.
output +=
  '// prettier-ignore\nfunction testFormat(format, value) { return typeof format === "function" ? format(value) : format.test(value); }\n'
const factories = new Map()
for (const group of groups.values()) {
  const ajv = new Ajv({ ...group[0].options, sourceCode: true })
  const registered = new Set()
  for (const definition of group) {
    for (const ref of definition.refs ?? []) {
      const key = JSON.stringify(ref)
      if (!registered.has(key)) {
        ajv.addSchema(ref)
        registered.add(key)
      }
    }
  }
  const roots = group.map((definition) => ajv.compile(definition.schema))
  // Some evidence schemas have recursive refs. Allocate every function first,
  // then link its closure variables, preserving Ajv's actual function/error refs.
  const graph = [...new Set(roots)]
  for (let i = 0; i < graph.length; i++) {
    for (const ref of graph[i].refVal) {
      if (typeof ref === 'function' && !graph.includes(ref)) graph.push(ref)
    }
  }
  const definition = group[0]
  let code = `const formats = formatsFactory(${JSON.stringify(definition.options.format ?? 'fast')}); const nodes: { validate: ValidateFunction; link: (refs: unknown[]) => void }[] = [];`
  for (const node of graph) {
    if (!node.source || node.source.customRules)
      throw new Error(`Unsupported compiler output: ${definition.name}`)
    const aliases = []
    let body = node.source.code.replace(
      /var (refVal\d+) = refVal\[(\d+)\];/g,
      (_, name, index) => {
        aliases.push([name, index])
        return ''
      },
    )
    // Keep tooling from inferring thousands of distinct error-object unions.
    // This annotation is erased by esbuild and leaves Ajv's function intact.
    if (body.split('var validate = function(').length !== 2)
      throw new Error(`Unexpected Ajv function declaration: ${definition.name}`)
    body = body.replace(
      'var validate = function(',
      'var validate: ValidateFunction = function(',
    )
    body = body.replace(
      /formats\[('[^']+')\](?:\.test)?\(/g,
      'testFormat(formats[$1], ',
    )
    const factory = `function(formats, schema) { let refVal; ${aliases.length ? `let ${aliases.map(([name]) => name).join(',')};` : ''} const validate: ValidateFunction = (() => { ${body} })(); validate.errors = null; validate.schema = schema; return { validate, link: (refs) => { refVal = refs; ${aliases.map(([name, index]) => `${name} = refs[${index}];`).join('')} } }; }`
    if (!factories.has(factory)) {
      const name = `validatorFactory${factories.size}`
      factories.set(factory, name)
      output += `// prettier-ignore\nconst ${name} = ${factory};\n`
    }
    code += `nodes.push(${factories.get(factory)}(formats, ${schemaValue(node.schema)}));`
  }
  for (const [index, node] of graph.entries()) {
    const refs = node.refVal.map((ref) =>
      typeof ref === 'function'
        ? `nodes[${graph.indexOf(ref)}].validate`
        : schemaValue(ref),
    )
    code += `nodes[${index}].link([${refs.join(',')}]);`
  }
  output += `// prettier-ignore\nexport const [${group.map((definition) => definition.name).join(', ')}]: ValidateFunction[] = (() => { ${code} return [${roots.map((root) => `nodes[${graph.indexOf(root)}].validate`).join(',')}]; })();\n`
}
output +=
  rules
    .map(
      ([names]) => `/* eslint-enable ${names} -- End of generated Ajv code */`,
    )
    .join('\n') + '\n'
const target = 'src/validation/generated/schemaValidators.ts'
if (process.argv.includes('--check')) {
  if (
    !fs.existsSync(target) ||
    fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output
  ) {
    throw new Error(
      'Generated validators are stale: node scripts/build-schema-validators.mjs',
    )
  }
} else {
  fs.writeFileSync(target, output)
}
console.log(
  `${target}: ${definitions.length} validators${process.argv.includes('--check') ? ' current' : ' generated'}`,
)
