import path from 'path'
import esbuild from 'esbuild'
import process from 'process'
import { builtinModules } from 'node:module'
import fs from 'fs'
import crypto from 'crypto'
import { readBuildProvenance } from './scripts/build-provenance.mjs'

const builtins = builtinModules.map((name) => name.replace(/^node:/, ''))
const nodeBuiltins = [...new Set([...builtins, ...builtins.map((mod) => `node:${mod}`)])].sort()

import { pgliteShimPlugin } from './scripts/pglite-shim.mjs'
import { checkPgliteWasm } from './scripts/check-pglite-wasm.mjs'

await checkPgliteWasm()


const banner = [
  '/*',
  'THIS IS A GENERATED/BUNDLED FILE BY ESBUILD',
  'if you want to view the source, please visit the github repository of this plugin',
  '*/',
  '',
].join('\n')

const prod = process.argv[2] === 'production'
const manifest = JSON.parse(fs.readFileSync(path.resolve('manifest.json'), 'utf8'))
const { source, dirty, builtAt } = readBuildProvenance()
const artifactPlaceholder = '__VERBEX_ARTIFACT_PENDING__'

/**
 * PGlite runtime resources (WASM, filesystem bundle, vector extension) are
 * loaded at runtime, not bundled into main.js. Copy them next to main.js so
 * they ship with the plugin and can be loaded from the plugin folder in
 * offline (air-gapped) environments where the unpkg CDN is unreachable.
 * These must come from the installed node_modules so their version always
 * matches the bundled PGlite JS client.
 */
const PGLITE_RESOURCE_FILES = ['postgres.data', 'postgres.wasm', 'vector.tar.gz']
const pgliteDistDir = path.resolve('node_modules/@electric-sql/pglite/dist')
for (const file of PGLITE_RESOURCE_FILES) {
  fs.copyFileSync(path.join(pgliteDistDir, file), path.resolve(file))
}

// Keep the lite tokenizer client and its runtime rank table on the same
// installed js-tiktoken version without bundling the 1 MB literal into main.js.
const { default: cl100kBase } = await import('js-tiktoken/ranks/cl100k_base')
fs.writeFileSync(
  path.resolve('cl100k_base.json'),
  JSON.stringify(cl100kBase),
)

// Offline local embedding runtime. Keep model and native runtime next to the worker.
const localEmbeddingDir = path.resolve('local-embedding')
fs.rmSync(localEmbeddingDir, { recursive: true, force: true })
fs.mkdirSync(path.join(localEmbeddingDir, 'models'), { recursive: true })
fs.cpSync('vendor/multilingual-e5-small', path.join(localEmbeddingDir, 'models/multilingual-e5-small'), { recursive: true })
const modelDir = path.join(localEmbeddingDir, 'models/multilingual-e5-small/onnx')
const fp16Parts = ['part1', 'part2', 'part3']
const fp16Bytes = Buffer.concat(fp16Parts.map((part) => fs.readFileSync(path.join(modelDir, `model_fp16.onnx.${part}`))))
if (crypto.createHash('sha256').update(fp16Bytes).digest('hex') !== '0e0fe349c99ea21c6f3aa273af21f7fb753c1e1174ef1647032029c2be3251c3') throw new Error('Local E5 FP16 checksum mismatch')
fs.writeFileSync(path.join(modelDir, 'model_fp16.onnx'), fp16Bytes)
for (const part of fp16Parts) fs.unlinkSync(path.join(modelDir, `model_fp16.onnx.${part}`))

fs.copyFileSync('assets/local-embedding/worker.cjs', path.join(localEmbeddingDir, 'worker.cjs'))
fs.copyFileSync('assets/local-embedding/gpu-worker.mjs', path.join(localEmbeddingDir, 'gpu-worker.mjs'))
fs.copyFileSync('node_modules/@huggingface/transformers/dist/transformers.js', path.join(localEmbeddingDir, 'transformers.web.js'))
for (const file of ['ort-wasm-simd-threaded.jsep.mjs', 'ort-wasm-simd-threaded.jsep.wasm']) {
  fs.copyFileSync(path.join('node_modules/onnxruntime-web/dist', file), path.join(localEmbeddingDir, file))
}
fs.copyFileSync('assets/local-embedding/ONNXRUNTIME-LICENSE', path.join(localEmbeddingDir, 'ONNXRUNTIME-LICENSE'))
fs.copyFileSync('assets/local-embedding/NODE-LICENSE', path.join(localEmbeddingDir, 'NODE-LICENSE'))
const nodeExecutable = fs.readFileSync('vendor/node-win-x64/node.exe')
if (crypto.createHash('sha256').update(nodeExecutable).digest('hex') !== '58e74bf02fc5bbacc41dcb8bef089961cd5bddd37830b87784e4fc624d145d1f') throw new Error('Bundled Node.js checksum mismatch')
fs.writeFileSync(path.join(localEmbeddingDir, 'node.exe'), nodeExecutable)
const bundledModules = path.join(localEmbeddingDir, 'node_modules')
const transformerDir = path.join(bundledModules, '@huggingface/transformers')
fs.mkdirSync(path.join(transformerDir, 'dist'), { recursive: true })
for (const file of ['package.json', 'LICENSE', 'dist/transformers.node.cjs']) {
  fs.copyFileSync(path.join('node_modules/@huggingface/transformers', file), path.join(transformerDir, file))
}
fs.cpSync('node_modules/onnxruntime-common', path.join(bundledModules, 'onnxruntime-common'), { recursive: true })
const onnxDir = path.join(bundledModules, 'onnxruntime-node')
fs.mkdirSync(path.join(onnxDir, 'bin/napi-v6/win32'), { recursive: true })
fs.copyFileSync('node_modules/onnxruntime-node/package.json', path.join(onnxDir, 'package.json'))
fs.cpSync('node_modules/onnxruntime-node/dist', path.join(onnxDir, 'dist'), { recursive: true })
fs.cpSync('node_modules/onnxruntime-node/bin/napi-v6/win32/x64', path.join(onnxDir, 'bin/napi-v6/win32/x64'), { recursive: true })
// The packaged Transformers.js build imports sharp even for text-only models.
// No image pipeline is exposed by this worker; avoid platform-specific image binaries.
const sharpDir = path.join(localEmbeddingDir, 'node_modules/sharp')
fs.mkdirSync(sharpDir, { recursive: true })
fs.writeFileSync(path.join(sharpDir, 'index.js'), "module.exports = () => { throw new Error('Image processing is unavailable') }\n")

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ['src/main.ts'],
  bundle: true,
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    '@lexical/clipboard/clipboard',
    ...nodeBuiltins,
  ],
  format: 'cjs',
  inject: [path.resolve('import-meta-url-shim.js')],
  define: {
    'import.meta.url': 'import_meta_url',
    'process.env.NODE_ENV': JSON.stringify(prod ? 'production' : 'development'),
    __VERBEX_VERSION__: JSON.stringify(manifest.version),
    __VERBEX_SOURCE__: JSON.stringify(source),
    __VERBEX_DIRTY__: JSON.stringify(dirty),
    __VERBEX_BUILT_AT__: JSON.stringify(builtAt),
    __VERBEX_ARTIFACT__: JSON.stringify(artifactPlaceholder),
  },
  target: 'es2020',
  logLevel: 'info', // 'debug' for more detailed output
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  outfile: 'main.js',
  minify: prod,
  metafile: true,
  plugins: [pgliteShimPlugin({ mainThread: true })],
})

const workerContext = await esbuild.context({
  entryPoints: ['src/database/pglite-worker.ts'],
  bundle: true,
  format: 'esm',
  target: 'es2020',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  outfile: 'pglite-worker.js',
  plugins: [pgliteShimPlugin()],
})

if (prod) {
  const result = await context.rebuild()
  await workerContext.rebuild()
  await workerContext.dispose()
  const bundlePath = path.resolve('main.js')
  const unstampedBundle = fs.readFileSync(bundlePath)
  const artifact = crypto
    .createHash('sha256')
    .update(unstampedBundle)
    .digest('hex')
    .slice(0, 12)
  const rawBundle = unstampedBundle.toString('utf8')
  const stampedBundle = rawBundle.replace(
    artifactPlaceholder,
    artifact.padEnd(artifactPlaceholder.length, ' '),
  )
  if (stampedBundle === rawBundle) {
    throw new Error('Verbex artifact placeholder was not found in main.js')
  }
  fs.writeFileSync(bundlePath, stampedBundle)
  const finalSha256 = crypto
    .createHash('sha256')
    .update(stampedBundle)
    .digest('hex')
  fs.writeFileSync(
    'build-info.json',
    JSON.stringify(
      {
        version: manifest.version,
        source,
        dirty,
        builtAt,
        artifact,
        finalSha256,
      },
      null,
      2,
    ),
  )
  fs.writeFileSync('meta.json', JSON.stringify(result.metafile))
  process.exit(0)
} else {
  await Promise.all([context.watch(), workerContext.watch()])
}
